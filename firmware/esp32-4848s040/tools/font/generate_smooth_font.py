from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


FONT_SIZES = (11, 13, 15, 18)
FONT_WEIGHT = 600
FIRST_CHARACTER = 32
LAST_CHARACTER = 126

script_directory = Path(__file__).resolve().parent
firmware_directory = script_directory.parents[1]
font_path = script_directory / "CascadiaMono.ttf"
output_path = firmware_directory / "src" / "smooth_font_data.h"


def packed_alpha(bitmap):
    values = [min(15, (value + 8) // 17) for value in bitmap.get_flattened_data()]
    output = bytearray()
    for index in range(0, len(values), 2):
        high = values[index]
        low = values[index + 1] if index + 1 < len(values) else 0
        output.append((high << 4) | low)
    return output


def render_font(size):
    font = ImageFont.truetype(str(font_path), size)
    font.set_variation_by_axes([FONT_WEIGHT])
    ascent, descent = font.getmetrics()
    glyphs = []
    bitmap = bytearray()

    for codepoint in range(FIRST_CHARACTER, LAST_CHARACTER + 1):
        character = chr(codepoint)
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        width = max(0, right - left)
        height = max(0, bottom - top)
        offset = len(bitmap)
        if width and height:
            image = Image.new("L", (width, height), 0)
            draw = ImageDraw.Draw(image)
            draw.text((-left, -top), character, font=font, fill=255, anchor="ls")
            bitmap.extend(packed_alpha(image))
        glyphs.append((offset, width, height, left, top, round(font.getlength(character))))

    return {
        "size": size,
        "ascent": ascent,
        "descent": descent,
        "line_height": ascent + descent,
        "glyphs": glyphs,
        "bitmap": bitmap,
    }


def bytes_literal(values):
    lines = []
    for index in range(0, len(values), 16):
        chunk = values[index:index + 16]
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in chunk) + ",")
    return "\n".join(lines)


def generate_header(fonts):
    output = [
        "// Generated by tools/font/generate_smooth_font.py. Do not edit manually.",
        "// Source: unmodified Cascadia Mono under the SIL Open Font License 1.1.",
        "#pragma once",
        "",
        "#include \"smooth_font.h\"",
        "",
        "namespace ccmeter {",
        "",
    ]

    for font in fonts:
        size = font["size"]
        output.extend([
            f"const uint8_t kSmoothFont{size}Bitmap[] PROGMEM = {{",
            bytes_literal(font["bitmap"]),
            "};",
            "",
            f"const SmoothGlyph kSmoothFont{size}Glyphs[] PROGMEM = {{",
        ])
        for offset, width, height, left, top, advance in font["glyphs"]:
            output.append(f"    {{{offset}, {width}, {height}, {left}, {top}, {advance}}},")
        output.extend([
            "};",
            "",
            f"const SmoothFont kSmoothFont{size} = {{",
            f"    {FIRST_CHARACTER}, {LAST_CHARACTER}, {font['ascent']}, {font['descent']}, {font['line_height']},",
            f"    kSmoothFont{size}Glyphs, kSmoothFont{size}Bitmap,",
            "};",
            "",
        ])

    output.extend(["}  // namespace ccmeter", ""])
    return "\n".join(output)


def main():
    if not font_path.exists():
        raise SystemExit(f"Missing font source: {font_path}")
    fonts = [render_font(size) for size in FONT_SIZES]
    output_path.write_text(generate_header(fonts), encoding="utf-8", newline="\n")
    total_bytes = sum(len(font["bitmap"]) for font in fonts)
    print(f"Wrote {output_path} with {total_bytes} packed alpha bytes")


if __name__ == "__main__":
    main()
